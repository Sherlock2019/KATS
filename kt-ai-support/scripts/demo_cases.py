"""The demo corpus. §40.

Twenty realistic cases across authentication, Kubernetes, database, network,
storage, API, certificate, DNS, CPU, memory, deployment, configuration,
permissions, cloud infrastructure and application failure.

The important part is the five near-twins. Cases 1-5 all present as "HTTP
404 could not find token" or something a keyword search cannot separate, and
they have five DIFFERENT root causes. They are separated only by IS / IS NOT:

    1  token persistence      new tokens fail      existing tokens work
    2  secret version drift   cluster A fails      cluster B works
    3  clock skew             one node fails       other nodes work
    4  cache eviction         after ~5 min fails   immediately after works
    5  load balancer routing  via LB fails         direct to pod works

Any retrieval that returns case 1 for a query describing case 3 is failing in
exactly the way §22 exists to prevent, and `tests/test_retrieval_kt.py`
asserts it does not.
"""

